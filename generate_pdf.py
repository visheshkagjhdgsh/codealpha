import os
from datetime import datetime
from typing import List, Tuple


def escape_pdf_text(text: str) -> str:
    return text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def build_pdf_objects(text_lines: List[Tuple[str, int, int, int]]) -> bytes:
    # PDF page size: LETTER 612x792 points
    objects: List[bytes] = []

    # 1 0 obj: Catalog
    objects.append(b"<< /Type /Catalog /Pages 2 0 R >>")

    # 2 0 obj: Pages
    objects.append(b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>")

    # 3 0 obj: Page
    page_obj = (
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>"
    )
    objects.append(page_obj)

    # 4 0 obj: Contents stream
    content_commands: List[str] = []
    for line, font_size, x, y in text_lines:
        content_commands.append(
            f"BT /F1 {font_size} Tf {x} {y} Td ({escape_pdf_text(line)}) Tj ET"
        )
    content_stream = "\n".join(content_commands).encode("latin-1")
    stream_dict = f"<< /Length {len(content_stream)} >>\nstream\n".encode("latin-1")
    stream_obj = stream_dict + content_stream + b"\nendstream"
    objects.append(stream_obj)

    # 5 0 obj: Font (Helvetica)
    objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")

    # Assemble file with xref
    pdf_header = b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n"
    file_bytes = bytearray()
    file_bytes.extend(pdf_header)

    offsets: List[int] = [0]  # object 0 is the free object at offset 0 by convention

    for index, obj in enumerate(objects, start=1):
        offsets.append(len(file_bytes))
        obj_entry = f"{index} 0 obj\n".encode("latin-1") + obj + b"\nendobj\n"
        file_bytes.extend(obj_entry)

    xref_start = len(file_bytes)
    num_entries = len(objects) + 1

    xref = [f"xref\n0 {num_entries}\n".encode("latin-1")]
    xref.append(b"0000000000 65535 f \n")
    for off in offsets[1:]:
        xref.append(f"{off:010d} 00000 n \n".encode("latin-1"))
    file_bytes.extend(b"".join(xref))

    trailer = (
        f"trailer\n<< /Size {num_entries} /Root 1 0 R >>\n"
        f"startxref\n{xref_start}\n%%EOF\n"
    ).encode("latin-1")
    file_bytes.extend(trailer)

    return bytes(file_bytes)


def generate_sample_pdf(output_filepath: str) -> None:
    timestamp = datetime.now().isoformat(timespec="seconds")
    lines = [
        ("Sample PDF", 24, 72, 720),
        ("Generated by your AI assistant.", 12, 72, 690),
        (f"Timestamp: {timestamp}", 12, 72, 672),
        ("This is a simple demonstration PDF.", 12, 72, 648),
    ]
    pdf_bytes = build_pdf_objects(lines)
    with open(output_filepath, "wb") as f:
        f.write(pdf_bytes)


if __name__ == "__main__":
    output_path = os.path.abspath(os.path.join(os.path.dirname(__file__), "sample.pdf"))
    generate_sample_pdf(output_path)
    print(f"Wrote {output_path}")